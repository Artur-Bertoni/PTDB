CREATE TABLE IF NOT EXISTS usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL,
    perfil VARCHAR(20) NOT NULL,
    CONSTRAINT uk_usuario_email UNIQUE (email),
    CONSTRAINT ck_usuario_perfil CHECK (perfil IN ('ADMINISTRADOR', 'AVALIADOR', 'ALUNO'))
);

CREATE TABLE IF NOT EXISTS categoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    descricao VARCHAR(255),
    ativa BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_categoria_nome UNIQUE (nome)
);

CREATE TABLE IF NOT EXISTS video (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(150) NOT NULL,
    descricao VARCHAR(4000) NOT NULL,
    autor VARCHAR(150) NOT NULL,
    categoria_id BIGINT NOT NULL,
    cadastrado_por_id BIGINT,
    origem_video VARCHAR(10) NOT NULL,
    arquivo_link VARCHAR(500) NOT NULL,
    nome_arquivo_original VARCHAR(255),
    imagem_capa VARCHAR(255),
    data_publicacao DATE NOT NULL,
    status VARCHAR(30) NOT NULL,
    data_cadastro TIMESTAMP NOT NULL,
    data_atualizacao TIMESTAMP,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_video_categoria FOREIGN KEY (categoria_id) REFERENCES categoria (id),
    CONSTRAINT fk_video_cadastrado_por FOREIGN KEY (cadastrado_por_id) REFERENCES usuario (id),
    CONSTRAINT ck_video_origem CHECK (origem_video IN ('LINK', 'ARQUIVO')),
    CONSTRAINT ck_video_status CHECK (status IN ('AGUARDANDO_AVALIACAO', 'AJUSTES_SOLICITADOS', 'APROVADO', 'REPROVADO'))
);

CREATE TABLE IF NOT EXISTS favorito (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,
    video_id BIGINT NOT NULL,
    data_registro TIMESTAMP NOT NULL,
    CONSTRAINT uk_favorito_usuario_video UNIQUE (usuario_id, video_id),
    CONSTRAINT fk_favorito_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE CASCADE,
    CONSTRAINT fk_favorito_video FOREIGN KEY (video_id) REFERENCES video (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS avaliacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    video_id BIGINT NOT NULL,
    avaliador_id BIGINT NOT NULL,
    decisao VARCHAR(30) NOT NULL,
    parecer VARCHAR(4000) NOT NULL,
    data TIMESTAMP NOT NULL,
    CONSTRAINT fk_avaliacao_video FOREIGN KEY (video_id) REFERENCES video (id),
    CONSTRAINT fk_avaliacao_avaliador FOREIGN KEY (avaliador_id) REFERENCES usuario (id),
    CONSTRAINT ck_avaliacao_decisao CHECK (decisao IN ('APROVADO', 'REPROVADO', 'AJUSTES_SOLICITADOS'))
);

CREATE TABLE IF NOT EXISTS faq (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pergunta VARCHAR(300) NOT NULL,
    resposta VARCHAR(4000) NOT NULL,
    categoria_tema VARCHAR(100),
    data_cadastro TIMESTAMP NOT NULL,
    data_atualizacao TIMESTAMP
);
